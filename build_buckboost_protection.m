%
%  保护逻辑出处（源码行号）：
%    ShortOff()  function.c:1280  判据 Iout>10.1A && Vout<0.5V
%    OTP()       function.c:1441  判据 Temp>=80℃
%    OVP()       function.c:1335  判据 Vout>=50V, 保持 OVPCnt>2 (15ms)
%    OCP()       function.c:1369  判据 Iout>=10.5A && SMFlag==Run, 保持 OCPCnt>10 (55ms)
%    StateM()    function.c:1044  状态机 Init/Wait/Rise/Run/Err
%    保护均在 TIM3 5ms 中断里执行 (main.c:287-296)
%    PWM 关断   PID.c:188-190    PWMENFlag==0 -> 占空比归零
%
%  【时间压缩说明】恢复/等待时间常数（短路/过流的 2s 恢复、1s 等待）
%   按 1/TSCALE 压缩以加速仿真（否则一次重启循环要跑真实 3s+ 开关级仿真，
%   墙钟时间不可接受）。判据保持时间（OVP 15ms / OCP 55ms）保持真实值，
%   这是保护响应的核心指标。TSCALE=20 -> 恢复 2s→100ms、等待 1s→50ms。
%
%  4 个场景（SCENES 可选，先跑 1 验证）：
%   1 = OVP       Vref 斜坡 12->52V，Vout 越 50V 触发 OVP，锁死不恢复
%   2 = OCP       负载突加 1ohm（Iout 冲 12A>10.5A），55ms 关断，恢复重启
%   3 = ShortOff  负载突加 0.1ohm（Vout<0.5V 且 Iout>10.1A），立即关断，恢复重启
%   4 = OTP       虚拟温度斜坡 25->85℃，越 80℃ 触发 OTP，锁死
% =====================================================================
