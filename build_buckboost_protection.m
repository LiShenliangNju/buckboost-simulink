%% ================= 控制器代码（保护 + 状态机 + 双环，照搬源码） =================
script = sprintf([ ...
'function [D_Q2, D_Q5, mode_out, sm_out, err_out] = BB_LoopCtl(Vout, Iout, Vref_set, Iref_set, Vin, Temp)\n' ...
'%% 四开关 Buck-Boost 双环 + 保护 + 状态机（照搬 zeruns）\n' ...
'persistent VErr1 VErr2 u1 Integral IErr1 ramp BBFlag softstart_done\n' ...
'persistent prot_cnt sm_flag pwm_en ovp_cnt ocp_cnt rs_cnt rs_num wait_cnt\n' ...
'persistent f_ovp f_ocp f_short f_otp\n' ...
'if isempty(VErr1)\n' ...
'    VErr1 = 0; VErr2 = 0; u1 = 0; Integral = 0; IErr1 = 0;\n' ...
'    ramp = 0; BBFlag = 0; softstart_done = 0;\n' ...
'    prot_cnt = 0; sm_flag = 1; pwm_en = 0;   %% sm_flag=1 即 Wait（Init 已由 ValInit 完成）\n' ...
'    ovp_cnt = 0; ocp_cnt = 0; rs_cnt = 0; rs_num = 0; wait_cnt = 0;\n' ...
'    f_ovp = 0; f_ocp = 0; f_short = 0; f_otp = 0;\n' ...
'end\n' ...
'%% 定点常量（PID.c / function.h）\n' ...
'BUCK_b0 = 5271;  BUCK_b1 = -10363;  BUCK_b2 = 5093;\n' ...
'BOOST_b0 = 8044; BOOST_b1 = -15813; BOOST_b2 = 7772;\n' ...
'ILOOP_KP = 6; ILOOP_KI = 3; ILOOP_KD = 1;\n' ...
'LSB_PER_V = 155.5;  LSB_PER_A = 769.2;  V_PER_LSB = 1/155.5;\n' ...
'PERIOD = 30000;  ADC_MAX = 8190;\n' ...
'DUTY_BUCK_MAX  = 28200/PERIOD;  DUTY_BUCK_MIN  = 100/PERIOD;\n' ...
'DUTY_BOOST_MAX = 19500/PERIOD;  DUTY_BOOST_MIN = 100/PERIOD;\n' ...
'DUTY_BOOST_FIX = 1800/PERIOD;   %% Buck 模式 Boost 下管固定 6%%\n' ...
'DUTY_BUCK_FIX  = 28200/PERIOD;  %% Boost 模式 Buck 上管固定 94%%\n' ...
'DUTY_MIX_FIX   = 24000/PERIOD;  %% Mix 模式 Buck 上管固定 80%%\n' ...
'U0_BUCK_MAX  = 28200*256/3;  U0_BOOST_MAX = 19500*256/3;\n' ...
'PROT_N = %d;  RSCNT_MAX = %d;  WAITCNT_MAX = %d;\n' ...
'%% ===== 5ms 保护 + 状态机节拍（TIM3 中断，main.c:290-295） =====\n' ...
'prot_cnt = prot_cnt + 1;\n' ...
'if prot_cnt >= PROT_N\n' ...
'    prot_cnt = 0;\n' ...
'    %% ---- 保护判定（源码顺序 ShortOff -> OTP -> OVP -> OCP）----\n' ...
'    if (Iout > 10.1) && (Vout < 0.5)      %% ShortOff：立即关断\n' ...
'        pwm_en = 0; f_short = 1; sm_flag = 4;\n' ...
'    end\n' ...
'    if Temp >= 80                          %% OTP：立即关断，锁死\n' ...
'        pwm_en = 0; f_otp = 1; sm_flag = 4;\n' ...
'    end\n' ...
'    if Vout >= 50                          %% OVP：保持 15ms\n' ...
'        ovp_cnt = ovp_cnt + 1;\n' ...
'        if ovp_cnt > 2\n' ...
'            ovp_cnt = 0; pwm_en = 0; f_ovp = 1; sm_flag = 4;\n' ...
'        end\n' ...
'    else\n' ...
'        ovp_cnt = 0;\n' ...
'    end\n' ...
'    if (Iout >= 10.5) && (sm_flag == 3)    %% OCP：仅 Run 状态计数，保持 55ms\n' ...
'        ocp_cnt = ocp_cnt + 1;\n' ...
'        if ocp_cnt > 10\n' ...
'            ocp_cnt = 0; pwm_en = 0; f_ocp = 1; sm_flag = 4;\n' ...
'        end\n' ...
'    else\n' ...
'        ocp_cnt = 0;\n' ...
'    end\n' ...
'    %% ---- 短路/过流自动恢复（2s 清标志，10 次重启锁死）----\n' ...
'    if (f_short == 1) || (f_ocp == 1)\n' ...
'        rs_cnt = rs_cnt + 1;\n' ...
'        if rs_cnt > RSCNT_MAX\n' ...
'            rs_cnt = 0; rs_num = rs_num + 1;\n' ...
'            if rs_num > 10\n' ...
'                rs_num = 11; pwm_en = 0;   %% 锁死\n' ...
'            else\n' ...
'                f_short = 0; f_ocp = 0;    %% 清故障标志\n' ...
'            end\n' ...
'        end\n' ...
'    end\n' ...
'    %% ---- 状态机 StateM（function.c:1044）----\n' ...
'    switch sm_flag\n' ...
'        case 1   %% Wait\n' ...
'            pwm_en = 0;\n' ...
'            wait_cnt = wait_cnt + 1;\n' ...
'            if wait_cnt > WAITCNT_MAX\n' ...
'                wait_cnt = WAITCNT_MAX;\n' ...
'                if (f_ovp==0)&&(f_ocp==0)&&(f_short==0)&&(f_otp==0)\n' ...
'                    wait_cnt = 0; sm_flag = 2;\n' ...
'                    softstart_done = 0; ramp = 0;  %% 重置软启动\n' ...
'                    VErr1 = 0; VErr2 = 0; u1 = 0; Integral = 0; IErr1 = 0;  %% 清零环路变量（StateMRise SSInit）\n' ...
'                end\n' ...
'            end\n' ...
'        case 2   %% Rise（软启动在快环 ramp 完成）\n' ...
'            pwm_en = 1;\n' ...
'            if softstart_done\n' ...
'                sm_flag = 3;\n' ...
'            end\n' ...
'        case 3   %% Run\n' ...
'            %% 正常运行，无操作\n' ...
'        case 4   %% Err\n' ...
'            pwm_en = 0;\n' ...
'            BBFlag = 0;   %% StateMErr 设 NA（BBMode 随后覆盖，与源码顺序一致）\n' ...
'            if (f_ovp==0)&&(f_ocp==0)&&(f_short==0)&&(f_otp==0)\n' ...
'                sm_flag = 1; wait_cnt = 0;\n' ...
'            end\n' ...
'    end\n' ...
'end\n' ...
'%% ===== BBMode 迟滞判定（快环，function.c:1463，用 Vref_set 近似 Vout_ref）=====\n' ...
'PreBBFlag = BBFlag;\n' ...
'switch BBFlag\n' ...
'    case 0\n' ...
'        if Vref_set < 0.8*Vin, BBFlag = 1;\n' ...
'        elseif Vref_set > 1.2*Vin, BBFlag = 2;\n' ...
'        else, BBFlag = 3; end\n' ...
'    case 1\n' ...
'        if Vref_set > 1.2*Vin, BBFlag = 2;\n' ...
'        elseif Vref_set > 0.85*Vin, BBFlag = 3; end\n' ...
'    case 2\n' ...
'        if Vref_set < 0.8*Vin, BBFlag = 1;\n' ...
'        elseif Vref_set < 1.15*Vin, BBFlag = 3; end\n' ...
'    case 3\n' ...
'        if Vref_set < 0.8*Vin, BBFlag = 1;\n' ...
'        elseif Vref_set > 1.2*Vin, BBFlag = 2; end\n' ...
'end\n' ...
'%% ===== 软启动 ramp（快环，120V/s 慢速，避免 2P2Z b1 负系数 bang-bang）=====\n' ...
'if ~softstart_done\n' ...
'    ramp = ramp + 120/181333;\n' ...
'    if ramp >= Vref_set, ramp = Vref_set; softstart_done = 1; end\n' ...
'end\n' ...
'if softstart_done, Vref_eff = Vref_set; else, Vref_eff = ramp; end\n' ...
'%% ===== 电流环（增量式 PID，内环）=====\n' ...
'IErr_LSB = (Iref_set - Iout) * LSB_PER_A;\n' ...
'i0_LSB = Integral + ILOOP_KP*IErr_LSB + ILOOP_KD*(IErr_LSB - IErr1);\n' ...
'Integral = Integral + ILOOP_KI*IErr_LSB;\n' ...
'if Integral > ADC_MAX, Integral = ADC_MAX; end\n' ...
'if Integral < 0, Integral = 0; end\n' ...
'IErr1 = IErr_LSB;\n' ...
'i0_V = i0_LSB * V_PER_LSB;\n' ...
'Vref_ctrl = Vref_eff + i0_V;\n' ...
'if Vref_ctrl > Vref_eff, Vref_ctrl = Vref_eff; end\n' ...
'if Vref_ctrl < 0, Vref_ctrl = 0; end\n' ...
'%% 模式切换清零积分（PID.c:102，电流环后、电压环前）\n' ...
'if BBFlag ~= PreBBFlag\n' ...
'    u1 = 0; Integral = 0;\n' ...
'end\n' ...
'%% ===== 电压环（2P2Z，按 BBFlag 选系数）=====\n' ...
'VErr_LSB = (Vref_ctrl - Vout) * LSB_PER_V;\n' ...
'if BBFlag == 1   %% Buck\n' ...
'    u0 = u1 + BUCK_b0*VErr_LSB + BUCK_b1*VErr1 + BUCK_b2*VErr2;\n' ...
'    if u0 > U0_BUCK_MAX, u0 = U0_BUCK_MAX; end\n' ...
'    if u0 < 0, u0 = 0; end\n' ...
'    VErr2 = VErr1; VErr1 = VErr_LSB; u1 = u0;\n' ...
'    D_Q2 = floor(u0/256)*3/PERIOD;  D_Q5 = DUTY_BOOST_FIX;\n' ...
'    if D_Q2 > DUTY_BUCK_MAX, D_Q2 = DUTY_BUCK_MAX; end\n' ...
'    if D_Q2 < DUTY_BUCK_MIN, D_Q2 = DUTY_BUCK_MIN; end\n' ...
'elseif BBFlag == 2   %% Boost\n' ...
'    u0 = u1 + BOOST_b0*VErr_LSB + BOOST_b1*VErr1 + BOOST_b2*VErr2;\n' ...
'    if u0 > U0_BOOST_MAX, u0 = U0_BOOST_MAX; end\n' ...
'    if u0 < 0, u0 = 0; end\n' ...
'    VErr2 = VErr1; VErr1 = VErr_LSB; u1 = u0;\n' ...
'    D_Q2 = DUTY_BUCK_FIX;  D_Q5 = floor(u0/256)*3/PERIOD;\n' ...
'    if D_Q5 > DUTY_BOOST_MAX, D_Q5 = DUTY_BOOST_MAX; end\n' ...
'    if D_Q5 < DUTY_BOOST_MIN, D_Q5 = DUTY_BOOST_MIN; end\n' ...
'else   %% Mix（Boost 系数，Q2 固定 80%%）\n' ...
'    u0 = u1 + BOOST_b0*VErr_LSB + BOOST_b1*VErr1 + BOOST_b2*VErr2;\n' ...
'    if u0 > U0_BOOST_MAX, u0 = U0_BOOST_MAX; end\n' ...
'    if u0 < 0, u0 = 0; end\n' ...
'    VErr2 = VErr1; VErr1 = VErr_LSB; u1 = u0;\n' ...
'    D_Q2 = DUTY_MIX_FIX;  D_Q5 = floor(u0/256)*3/PERIOD;\n' ...
'    if D_Q5 > DUTY_BOOST_MAX, D_Q5 = DUTY_BOOST_MAX; end\n' ...
'    if D_Q5 < DUTY_BOOST_MIN, D_Q5 = DUTY_BOOST_MIN; end\n' ...
'end\n' ...
'%% ===== PWM 关断（保护触发时 PWMENFlag=0 -> 占空比归零，PID.c:188）=====\n' ...
'if pwm_en == 0\n' ...
'    D_Q2 = 0; D_Q5 = 0;\n' ...
'end\n' ...
'mode_out = BBFlag;\n' ...
'sm_out = sm_flag;\n' ...
'err_out = f_ovp*8 + f_ocp*16 + f_short*32 + f_otp*64;  %% 对应源码 ErrFlag 位 0x08/0x10/0x20/0x40\n' ...
'end\n'], PROT_N, RSCNT_MAX, WAITCNT_MAX);

