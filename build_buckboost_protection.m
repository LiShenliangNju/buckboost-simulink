results = struct();
for k = SCENES
    c = scn(k);
    fprintf('\n========== 场景 %d：%s ==========\n', k, c.name);
    % 场景参数
    set_param([model '/Rfault'], 'Resistance', num2str(c.Rfault));
    set_param([model '/Iref'], 'Value', num2str(c.Iref));

    % Vref / Temp / 门控 时间序列（1ms 采样）
    t_ref = (0:1e-3:c.Tsim)';
    vref_data = [t_ref, c.vref(t_ref)];
    temp_data = [t_ref, c.temp(t_ref)];
    sw_seq = zeros(size(t_ref));                       % 门控脉冲：投入区间为 1
    if ~isempty(c.breaker_times)
        sw_seq(t_ref >= c.breaker_times(1) & t_ref < c.breaker_times(2)) = 1;
    end
    sw_data = [t_ref, sw_seq];
    set_param([model '/Vref'], 'VariableName', 'vref_data');
    set_param([model '/Temp'], 'VariableName', 'temp_data');
    set_param([model '/SwGate'], 'VariableName', 'sw_data');
    set_param(model, 'StopTime', num2str(c.Tsim));

    % 仿真
    simOut = sim(model);

    Vout_t = simOut.get('Vout_ts'); Iout_t = simOut.get('Iout_ts');
    DQ2_t  = simOut.get('DQ2_ts');  DQ5_t  = simOut.get('DQ5_ts');
    sm_t   = simOut.get('sm_ts');   err_t  = simOut.get('err_ts');
    IL_t   = simOut.get('IL_ts');   Vref_t = simOut.get('Vref_ts');

    results(k).Vout_t = Vout_t; results(k).Iout_t = Iout_t;
    results(k).DQ2_t = DQ2_t; results(k).DQ5_t = DQ5_t;
    results(k).sm_t = sm_t; results(k).err_t = err_t;
    results(k).IL_t = IL_t; results(k).Vref_t = Vref_t;
    results(k).name = c.name;

    % 分析：状态机 + 故障标志时序
    sm = round(sm_t.Data); err = round(err_t.Data);
    fprintf('状态机时序（0=Init 1=Wait 2=Rise 3=Run 4=Err）：\n');
    chg = find(diff(sm) ~= 0);
    prev_t = 0;
    for i = 1:numel(chg)
        fprintf('  t=%.3fs -> 状态 %d\n', sm_t.Time(chg(i)), sm(chg(i)+1));
    end
    fprintf('故障标志 ErrFlag 变化（0x08=OVP 0x10=OCP 0x20=Short 0x40=OTP）：\n');
    e_chg = find(diff(err) ~= 0);
    for i = 1:numel(e_chg)
        fprintf('  t=%.3fs -> ErrFlag=0x%02X\n', err_t.Time(e_chg(i)), err(e_chg(i)+1));
    end
    % 关断时刻（D 归零）与 Vout 峰值
    dq5 = DQ5_t.Data;
    t5 = DQ5_t.Time;
    off_idx = find(dq5 < 1e-3, 1);
    if ~isempty(off_idx)
        fprintf('PWM 首次关断时刻：t=%.4fs\n', t5(off_idx));
    end
    fprintf('Vout 峰值 = %.2fV\n', max(Vout_t.Data));
end

